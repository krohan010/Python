# Variables are containers for storing data values..

# There is no keyword to specify that an variable
# only assigning some value to the variable is variable..
num = 58
str = "Hello World"
print(num)
print(str)

# type of variable
print(type(num))
print(type(str))

# single or double quotes will be same
str1 = 'String'
str2 = "String"

if str1 == str2:
    print("Both are same")

# case sensitivity :
num = 10
NUM = 52
print(num)
print(NUM)