# Type Casting -> it means that sometimes we need to change the datatype of an variable 
# so we use this method

# Integer type casting..
x = int(1)                  # 1
y = int(4.2)                # 4
z = int("15")               # 15
# print(x, y, z)

# Float Type Casting...
a = float(1)                # 1.0
b = float(2.1)              # 2.1
c = float("3")              # 3.0
d = float("4.4")            # 4.4
# print(a, b, c, d)

# String Type Casting..
a = str(1)                  # "1"
b = str(2.5)                # "2.5"
c = str("Text")             # "Text"
# print(a, b, c)