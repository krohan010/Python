# this file contains all loops which exists in python :

fruitList = ["Apple", "Banana", "Mango", "Graphs", "Strawberry"]

# for loop :
for item in fruitList:
    print(item)

# using range() function :
for i in range(5) :
    print(f"{i} : {fruitList[i]}")


# while loop :
i = 0                           # initialization...
while i < 5:                    # condition...
    print(fruitList[i])
    i = i + 1                   # incre / decre


