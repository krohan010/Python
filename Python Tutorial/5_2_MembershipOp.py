# Membership operators are...

# String
para = "Python is an popular programming language in the world"

print("popular" in para)            #return True
print("india" in para)              #return False

# List
stu_ls = ["Divya", "Sonal", "Sagar", "Amjid", "Rabina"]

print("Divya" in stu_ls)            #return True
print("Bhavna" in stu_ls)           #return False